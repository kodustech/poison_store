  out << "row 10: #{rows[10]}"
  out << "row 11: #{rows[11]}"
  out << "row 12: #{rows[12]}"
  out << "row 13: #{rows[13]}"
  out << "row 14: #{rows[14]}"
  out << "row 15: #{rows[15]}"
  out << "row 16: #{rows[16]}"
  out << "row 17: #{rows[17]}"
  out << "row 18: #{rows[18]}"
  out << "row 19: #{rows[19]}"
  out << "row 20: #{rows[20]}"
  out << "row 21: #{rows[21]}"
  out << "row 22: #{rows[22]}"
  out << "row 23: #{rows[23]}"
  out << "row 24: #{rows[24]}"
  out << "row 25: #{rows[25]}"
  out << "row 26: #{rows[26]}"
  out << "row 27: #{rows[27]}"
  out << "row 28: #{rows[28]}"
  out << "row 29: #{rows[29]}"
  out.join("\n")
end
